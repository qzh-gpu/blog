/*
 * 【原理说明 - 排序 + 贪心插入】
 * 1. 核心矛盾：矮个子插入到高个子前面，不会影响高个子前面“比他高的人数”（因为矮个子不算）。
 *    所以我们先处理所有高个子，再插入矮个子。
 *
 * 2. 排序规则（关键）：
 *    - 按身高 h 从高到低降序排列（高的先站队）。
 *    - 如果身高相同 h 相等，按 k 值从小到大升序排列（k 小的先插）。
 *
 * 3. 插入规则：
 *    - 遍历排序后的数组，对于每个人 [h, k]，
 *      直接将他插入到当前结果队列的索引 k 的位置。
 *    - 为什么可以这么做？因为当前队列里所有人的身高都 >= h，
 *      此时把他放到索引 k，他前面正好有 k 个人比他高或相等。
 *
 * 4. 时间复杂度 O(n²)（List 插入是 O(n)，n ≤ 2000 可行），空间 O(n)。
 */

import java.util.*;

class Solution {
    public int[][] reconstructQueue(int[][] people) {
        // 1. 排序：身高从高到低，身高相同则 k 从小到大
        Arrays.sort(people, (a, b) -> {
            // a[0] 是身高 h，a[1] 是 k
            if (a[0] != b[0]) {
                // 身高不同：高的排前面（降序），b[0] - a[0]
                return b[0] - a[0];
            } else {
                // 身高相同：k 小的排前面（升序），a[1] - b[1]
                return a[1] - b[1];
            }
        });

        // 2. 创建结果列表，用于按 k 插入
        List<int[]> queue = new ArrayList<>();

        // 3. 遍历排序后的数组
        for (int[] p : people) {
            // 直接插入到索引 p[1] 的位置
            // 因为当前列表中所有人的身高都 >= p[0]
            queue.add(p[1], p);
        }

        // 4. 将 List 转为二维数组返回
        return queue.toArray(new int[queue.size()][]);
    }
}